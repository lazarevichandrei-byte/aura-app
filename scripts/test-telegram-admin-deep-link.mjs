import assert from "node:assert/strict";
import fs from "node:fs";
import {createRequire} from "node:module";
import path from "node:path";

const outputDirectory=process.argv[2];if(!outputDirectory)throw new Error("OUTPUT_DIRECTORY_REQUIRED");
const require=createRequire(import.meta.url);
const {telegramLaunchContextV1,resolveTelegramStartupRouteV1,hasAdminTelegramStartIntentV1}=require(path.resolve(outputDirectory,"telegram-deep-link.js"));
const telegram=(start_param)=>({initDataUnsafe:{user:{id:123},start_param}});
const admin=telegramLaunchContextV1("signed-init-data",telegram("admin"));
assert.equal(hasAdminTelegramStartIntentV1(admin),true);
assert.equal(resolveTelegramStartupRouteV1({context:admin,userExists:true,onboardingCompleted:true,currentPath:"/"}),"/admin/aura","admin deep link");
const normal=telegramLaunchContextV1("signed-init-data",telegram(undefined));
assert.equal(resolveTelegramStartupRouteV1({context:normal,userExists:true,onboardingCompleted:true,currentPath:"/"}),"/home","normal launch unchanged");
const unknown=telegramLaunchContextV1("signed-init-data",telegram("meet-123"));
assert.equal(resolveTelegramStartupRouteV1({context:unknown,userExists:true,onboardingCompleted:true,currentPath:"/"}),"/home","unknown launch unchanged");
const browser=telegramLaunchContextV1("",telegram("admin"));
assert.deepEqual(browser,{hasTelegramContext:false,startParam:null});
assert.equal(resolveTelegramStartupRouteV1({context:browser,userExists:true,onboardingCompleted:true,currentPath:"/"}),"/home","browser is not redirected to admin");
assert.equal(resolveTelegramStartupRouteV1({context:admin,userExists:false,onboardingCompleted:false,currentPath:"/"}),null,"welcome/registration wins");
assert.equal(resolveTelegramStartupRouteV1({context:admin,userExists:true,onboardingCompleted:false,currentPath:"/"}),"/profile","onboarding wins");
assert.equal(resolveTelegramStartupRouteV1({context:admin,userExists:true,onboardingCompleted:true,currentPath:"/admin/aura"}),null,"no redirect loop");
const page=fs.readFileSync(path.resolve(process.cwd(),"app/page.tsx"),"utf8");
assert.match(page,/loadCurrentUser\(\{force:true\}\)[\s\S]*routeAuthenticatedUser\(user\)/,"route occurs after auth bootstrap");
assert.match(page,/savePendingRoute\("\/admin\/aura"\)/,"admin intent survives required onboarding");
assert.doesNotMatch(page,/start_param[\s\S]*(?:isAdmin|authorized|allowlist)/i,"start param is not admin proof");
const pending=fs.readFileSync(path.resolve(process.cwd(),"lib/auth/pendingRoute.ts"),"utf8");assert.match(pending,/admin\\\/aura/);
const bottomNav=fs.readFileSync(path.resolve(process.cwd(),"components/BottomNav.tsx"),"utf8");assert.doesNotMatch(bottomNav,/admin\/aura/i);
console.log("TELEGRAM_ADMIN_DEEP_LINK_TESTS_PASS");
